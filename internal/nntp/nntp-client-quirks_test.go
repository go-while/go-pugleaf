package nntp

// Provider-quirk tests of plan fetcher-hostile-peer, slice
// client-provider-quirks (design point 3): the client against the shapes real
// providers show, modelled by the kit's Store mode (nntp-testkit v0.5.0):
// generated groups with a span limit, StoreOptions.MaxOverRange /
// OverRangeTooLarge, ListgroupRange, EmptyOverReply, GroupNumbers and
// OverviewFields.
//
// These tests pin what the client does today; where the behaviour is a
// deviation from what a caller might expect, the test comment says so and the
// finding is in the slice report (the overview is a hint, the article's own
// Message-ID header is the truth: filing is wave 2).
//
// All servers are cliStoreServer instances on 127.0.0.1:0; no wall-clock
// assertion anywhere, cliWait is a hang guard only.

import (
	"errors"
	"fmt"
	"strconv"
	"strings"
	"testing"
	"time"
)

// cliQuirkRun runs f with cliWait as a hang guard: a passing test never waits
// on it, a hung client fails the test instead of blocking the package.
func cliQuirkRun(t *testing.T, what string, f func() error) error {
	t.Helper()
	done := make(chan error, 1)
	go func() {
		defer func() {
			if r := recover(); r != nil {
				done <- fmt.Errorf("panic in %s: %v", what, r)
			}
		}()
		done <- f()
	}()
	timer := time.NewTimer(cliWait)
	defer timer.Stop()
	select {
	case err := <-done:
		return err
	case <-timer.C:
		t.Fatalf("%s still blocked after %v", what, cliWait)
		return nil
	}
}

// cliQuirkPool builds a pool on cliBackend(s), closed by t.Cleanup.
func cliQuirkPool(t *testing.T, s *cliFakeServer) *Pool {
	t.Helper()
	cfg := cliBackend(s)
	cfg.AuthFailureBackoff = -1
	pool := NewPool(cfg)
	t.Cleanup(func() { _ = pool.ClosePool() })
	return pool
}

// cliQuirkFill stores articles from..to in group (Message-IDs generated by the
// kit as <n.group@fakeserver.invalid>).
func cliQuirkFill(st *cliFakeStore, group string, from, to int64) {
	st.AddGroup(group, "quirk test group")
	for n := from; n <= to; n++ {
		st.AddArticle(group, cliFakeArticle{
			Number: n,
			Headers: []string{
				"From: tester@quirk.invalid",
				fmt.Sprintf("Subject: article %d", n),
			},
			Body: []string{fmt.Sprintf("body of article %d", n)},
		})
	}
}

// cliQuirkNums returns the article numbers of ovs.
func cliQuirkNums(ovs []OverviewLine) []int64 {
	out := make([]int64, 0, len(ovs))
	for _, o := range ovs {
		out = append(out, o.ArticleNum)
	}
	return out
}

// cliQuirkCmdLines returns every client line of s whose first word is verb.
func cliQuirkCmdLines(s *cliFakeServer, verb string) []string {
	var out []string
	for _, l := range s.Lines() {
		if w, _, _ := strings.Cut(l, " "); strings.EqualFold(w, verb) {
			out = append(out, l)
		}
	}
	return out
}

// TestCliQuirkGeneratedSpans runs XOVER against a generated group of 150000
// articles whose Generator.Limit is the kit default (DefaultGenLimit 100000:
// a larger span gets 503).
func TestCliQuirkGeneratedSpans(t *testing.T) {
	const group = "gen.big"
	const high = int64(150000)

	newServer := func(t *testing.T) *cliFakeServer {
		st := cliFakeNewStore()
		st.AddGenerated(group, "generated group", cliFakeGenerator{Low: 1, High: high})
		return cliStoreServer(t, st, cliFakeStoreOpts{}, cliFakeFaults{})
	}

	t.Run("below-limit", func(t *testing.T) {
		s := newServer(t)
		pool := cliQuirkPool(t, s)
		var ovs []OverviewLine
		err := cliQuirkRun(t, "XOver 1-50", func() error {
			var e error
			ovs, e = pool.XOver(group, 1, 50, true)
			return e
		})
		if err != nil {
			t.Fatalf("XOver 1-50: %v", err)
		}
		if len(ovs) != 50 {
			t.Fatalf("XOver 1-50 returned %d lines, want 50", len(ovs))
		}
		for i, o := range ovs {
			if want := int64(i + 1); o.ArticleNum != want {
				t.Fatalf("line %d has number %d, want %d", i, o.ArticleNum, want)
			}
			if want := fmt.Sprintf("<%d.%s@fakeserver.invalid>", o.ArticleNum, group); o.MessageID != want {
				t.Fatalf("line %d has message-id %q, want %q", i, o.MessageID, want)
			}
		}
	})

	// A span far above DefaultGenLimit with enforceLimit: the client caps
	// every enforced span to MaxReadLinesXover (100 today), which is three
	// orders of magnitude below the kit's limit, so the 503 is never
	// reached. That is design point 3 ("a run that stays inside the limit is
	// never aborted by OverRangeTooLarge") by capping, not by splitting: the
	// caller gets only the first MaxReadLinesXover numbers and has to ask
	// again for the rest (the fetcher does, wave 2).
	t.Run("enforce-limit-caps-the-span", func(t *testing.T) {
		s := newServer(t)
		pool := cliQuirkPool(t, s)
		var ovs []OverviewLine
		err := cliQuirkRun(t, "XOver 1-high enforced", func() error {
			var e error
			ovs, e = pool.XOver(group, 1, high, true)
			return e
		})
		if err != nil {
			t.Fatalf("XOver 1-%d (enforceLimit): %v", high, err)
		}
		if int64(len(ovs)) != MaxReadLinesXover {
			t.Fatalf("XOver 1-%d (enforceLimit) returned %d lines, want MaxReadLinesXover=%d", high, len(ovs), MaxReadLinesXover)
		}
		if got := ovs[len(ovs)-1].ArticleNum; got != MaxReadLinesXover {
			t.Fatalf("last number is %d, want %d", got, MaxReadLinesXover)
		}
		want := fmt.Sprintf("XOVER 1-%d", MaxReadLinesXover)
		if got := cliQuirkCmdLines(s, "XOVER"); len(got) != 1 || got[0] != want {
			t.Fatalf("XOVER lines on the wire = %q, want [%q] (the over-limit span must never reach the server)", got, want)
		}
		// the capped call is a normal success: the connection stays in the pool
		if got := s.Accepted(); got != 1 {
			t.Fatalf("server accepted %d connections after the capped XOver, want 1 (no reconnect)", got)
		}
	})

	// Without enforceLimit the span reaches the server and the kit answers
	// 503. The client reports it as an error that names the 503 status line;
	// it is not ErrNoArticlesInRange and it is not an empty result.
	t.Run("no-enforce-limit-gets-503", func(t *testing.T) {
		s := newServer(t)
		pool := cliQuirkPool(t, s)
		var ovs []OverviewLine
		err := cliQuirkRun(t, "XOver 1-high unenforced", func() error {
			var e error
			ovs, e = pool.XOver(group, 1, high, false)
			return e
		})
		if err == nil {
			t.Fatalf("XOver 1-%d (no enforceLimit) returned %d lines and no error, want the 503", high, len(ovs))
		}
		if !strings.Contains(err.Error(), "503") {
			t.Fatalf("error %v does not name the 503 status line", err)
		}
		if errors.Is(err, ErrNoArticlesInRange) {
			t.Fatalf("503 over-limit span reported as ErrNoArticlesInRange: %v", err)
		}
		if ovs != nil {
			t.Fatalf("XOver returned %d lines next to the error", len(ovs))
		}
		// Pool.XOver force-closes the connection on this error although the
		// 503 status line left the session in a clean state; the next Get
		// therefore dials again. Documented, not asserted as desirable.
		var ovs2 []OverviewLine
		if err := cliQuirkRun(t, "XOver after 503", func() error {
			var e error
			ovs2, e = pool.XOver(group, 1, 10, true)
			return e
		}); err != nil {
			t.Fatalf("XOver after the 503: %v", err)
		}
		if len(ovs2) != 10 {
			t.Fatalf("XOver after the 503 returned %d lines, want 10", len(ovs2))
		}
		if s.Accepted() < 2 {
			t.Fatalf("Accepted()=%d after the 503, want a fresh connection (>=2)", s.Accepted())
		}
	})
}

// TestCliQuirkMaxOverRange covers StoreOptions.MaxOverRange: a provider that
// silently serves only the first N numbers of a range, and one that refuses
// the range with a 503.
func TestCliQuirkMaxOverRange(t *testing.T) {
	const group = "quirk.maxover"

	t.Run("silently-truncated", func(t *testing.T) {
		st := cliFakeNewStore()
		cliQuirkFill(st, group, 1, 20)
		s := cliStoreServer(t, st, cliFakeStoreOpts{MaxOverRange: 5}, cliFakeFaults{})
		pool := cliQuirkPool(t, s)
		var ovs []OverviewLine
		err := cliQuirkRun(t, "XOver 1-20", func() error {
			var e error
			ovs, e = pool.XOver(group, 1, 20, false)
			return e
		})
		// The server answered 224 with only the first 5 lines: the client
		// returns what it got and no error. The caller sees the short span
		// (last number 5 < 20) and must not take it for "the group ends here".
		if err != nil {
			t.Fatalf("XOver 1-20 with MaxOverRange 5: %v", err)
		}
		if got := cliQuirkNums(ovs); len(got) != 5 || got[0] != 1 || got[4] != 5 {
			t.Fatalf("numbers = %v, want 1..5", got)
		}
	})

	t.Run("refused-with-503", func(t *testing.T) {
		st := cliFakeNewStore()
		cliQuirkFill(st, group, 1, 20)
		so := cliFakeStoreOpts{
			MaxOverRange:      5,
			OverRangeTooLarge: []string{"503 Range too large, try fewer articles"},
		}
		s := cliStoreServer(t, st, so, cliFakeFaults{})
		pool := cliQuirkPool(t, s)
		var ovs []OverviewLine
		err := cliQuirkRun(t, "XOver 1-20 refused", func() error {
			var e error
			ovs, e = pool.XOver(group, 1, 20, false)
			return e
		})
		if err == nil {
			t.Fatalf("XOver 1-20 returned %d lines and no error, want the 503", len(ovs))
		}
		if !strings.Contains(err.Error(), "503") || !strings.Contains(err.Error(), "Range too large") {
			t.Fatalf("error %v does not name the 503 reply", err)
		}
		if errors.Is(err, ErrNoArticlesInRange) {
			t.Fatalf("503 reported as ErrNoArticlesInRange: %v", err)
		}
		// A span the server does accept still works afterwards.
		if err := cliQuirkRun(t, "XOver 1-5", func() error {
			var e error
			ovs, e = pool.XOver(group, 1, 5, false)
			return e
		}); err != nil {
			t.Fatalf("XOver 1-5 after the 503: %v", err)
		}
		if len(ovs) != 5 {
			t.Fatalf("XOver 1-5 returned %d lines, want 5", len(ovs))
		}
	})
}

// TestCliQuirkListgroupRange covers StoreOptions.ListgroupRange: providers
// that refuse the range form of LISTGROUP with a 501, and providers that
// ignore the range and answer with the whole group.
func TestCliQuirkListgroupRange(t *testing.T) {
	const group = "quirk.listgroup"

	t.Run("reject", func(t *testing.T) {
		st := cliFakeNewStore()
		cliQuirkFill(st, group, 1, 5)
		s := cliStoreServer(t, st, cliFakeStoreOpts{ListgroupRange: "reject"}, cliFakeFaults{})
		c, err := cliDial(t, s, func(cfg *BackendConfig) { cfg.AuthFailureBackoff = -1 })
		if err != nil {
			t.Fatalf("Connect: %v", err)
		}
		var nums []int64
		err = cliQuirkRun(t, "ListGroup 1-5", func() error {
			var e error
			nums, e = c.ListGroup(group, 1, 5)
			return e
		})
		// The 501 must be an error, never "the group is empty".
		if err == nil {
			t.Fatalf("ListGroup with a range got %v and no error, want the 501", nums)
		}
		if !strings.Contains(err.Error(), "501") {
			t.Fatalf("error %v does not name the 501 reply", err)
		}
		if len(nums) != 0 {
			t.Fatalf("ListGroup returned %v next to the error", nums)
		}
		// The 501 status line was read completely: the connection is still
		// usable and the caller can fall back to the whole-group form.
		err = cliQuirkRun(t, "ListGroup fallback", func() error {
			var e error
			nums, e = c.ListGroup(group, 0, 0)
			return e
		})
		if err != nil {
			t.Fatalf("ListGroup fallback without a range: %v", err)
		}
		if len(nums) != 5 || nums[0] != 1 || nums[4] != 5 {
			t.Fatalf("fallback numbers = %v, want 1..5", nums)
		}
	})

	t.Run("ignore", func(t *testing.T) {
		st := cliFakeNewStore()
		cliQuirkFill(st, group, 1, 5)
		s := cliStoreServer(t, st, cliFakeStoreOpts{ListgroupRange: "ignore"}, cliFakeFaults{})
		c, err := cliDial(t, s, func(cfg *BackendConfig) { cfg.AuthFailureBackoff = -1 })
		if err != nil {
			t.Fatalf("Connect: %v", err)
		}
		var nums []int64
		err = cliQuirkRun(t, "ListGroup 2-3", func() error {
			var e error
			nums, e = c.ListGroup(group, 2, 3)
			return e
		})
		// The server ignored the range and sent the whole group: the extra
		// numbers are data, not an error. The caller has to filter.
		if err != nil {
			t.Fatalf("ListGroup 2-3 with ListgroupRange ignore: %v", err)
		}
		if len(nums) != 5 || nums[0] != 1 || nums[4] != 5 {
			t.Fatalf("numbers = %v, want the whole group 1..5", nums)
		}
	})
}

// TestCliQuirkEmptyOverReply covers StoreOptions.EmptyOverReply: a provider
// that answers an empty range with "224" and no overview lines instead of the
